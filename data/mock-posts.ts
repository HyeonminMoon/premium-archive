/** 홈 목록에 쓸 데이터. 본문(content)은 아예 빼고 내보낸다. */
export type PostSummary = Omit<Post, 'content'>;

export function getPostsForList(): PostSummary[] {
  return mockPosts
    // 필요한 값만 골라 담는다. content는 담지 않는다.
    .map((post) => ({
      id: post.id,
      title: post.title,
      summary: post.summary,
      createdAt: post.createdAt,
      isPremium: post.isPremium,
    }))
    .sort((a, b) => b.createdAt.localeCompare(a.createdAt)); // 최신순
}

/** 글 상세에 쓸 데이터. locked가 true면 body는 맛보기뿐이다. */
export type PostForReader = PostSummary & {
  body: string;
  locked: boolean;
};

export function getPostForReader(
  id: number,
  hasMembership: boolean,
): PostForReader | null {
  const post = mockPosts.find((p) => p.id === id);
  if (!post) return null;

  const { content, ...rest } = post;
  const canRead = !post.isPremium || hasMembership;

  return {
    ...rest,
    // 권한이 없으면 첫 문단(맛보기)만 담는다. 나머지는 서버 밖으로 나가지 않는다.
    body: canRead ? content : content.split('\n\n')[0],
    locked: !canRead,
  };
}
